import 'package:cashspark/domain/entities/user_entity.dart';

class UserModel extends UserEntity {
  const UserModel({
    required super.uid,
    super.firstName = '',
    super.lastName = '',
    super.fullName = '',
    required super.email,
    super.phone,
    required super.referralCode,
    super.referralCodeUsed,
    required super.createdAt,
    super.lastLoginAt,
    super.walletBalance = 0.0,
    super.totalEarnings = 0.0,
    super.totalWithdrawn = 0.0,
    super.isEmailVerified = false,
    super.isActive = true,
    super.profileCompleted = false,
    super.dateOfBirth,
    super.gender,
    super.address,
    super.city,
    super.state,
    super.country,
    super.username,
    super.profilePicture,
    super.coverImage,
    super.aboutMe,
    super.education,
    super.experience,
    super.portfolioLinks = const [],
    super.resumeUrl,
    super.certificateUrl,
    super.isVerified = false,
    super.profileCompletionPercentage = 0,
  });

  factory UserModel.fromEntity(UserEntity entity) {
    return UserModel(
      uid: entity.uid,
      firstName: entity.firstName,
      lastName: entity.lastName,
      fullName: entity.fullName,
      email: entity.email,
      phone: entity.phone,
      referralCode: entity.referralCode,
      referralCodeUsed: entity.referralCodeUsed,
      createdAt: entity.createdAt,
      lastLoginAt: entity.lastLoginAt,
      walletBalance: entity.walletBalance,
      totalEarnings: entity.totalEarnings,
      totalWithdrawn: entity.totalWithdrawn,
      isEmailVerified: entity.isEmailVerified,
      isActive: entity.isActive,
      profileCompleted: entity.profileCompleted,
      dateOfBirth: entity.dateOfBirth,
      gender: entity.gender,
      address: entity.address,
      city: entity.city,
      state: entity.state,
      country: entity.country,
      username: entity.username,
      profilePicture: entity.profilePicture,
      coverImage: entity.coverImage,
      aboutMe: entity.aboutMe,
      education: entity.education,
      experience: entity.experience,
      portfolioLinks: entity.portfolioLinks,
      resumeUrl: entity.resumeUrl,
      certificateUrl: entity.certificateUrl,
      isVerified: entity.isVerified,
      profileCompletionPercentage: entity.profileCompletionPercentage,
    );
  }

  factory UserModel.fromFirestore(Map<String, dynamic> map, {bool isEmailVerified = false}) {
    final portfolioList = (map['portfolioLinks'] as List<dynamic>?)?.map((e) => e.toString()).toList() ?? [];
    return UserModel(
      uid: map['uid'] as String? ?? '',
      firstName: map['firstName'] as String? ?? '',
      lastName: map['lastName'] as String? ?? '',
      fullName: map['fullName'] as String? ?? '',
      email: map['email'] as String? ?? '',
      phone: map['phone'] as String?,
      referralCode: map['referralCode'] as String? ?? '',
      referralCodeUsed: map['referralCodeUsed'] as String?,
      createdAt: (map['createdAt'] as dynamic) != null
          ? (map['createdAt'] as dynamic).toDate() as DateTime
          : DateTime.now(),
      lastLoginAt: (map['lastLoginAt'] as dynamic) != null
          ? (map['lastLoginAt'] as dynamic).toDate() as DateTime
          : null,
      walletBalance: (map['walletBalance'] as num?)?.toDouble() ?? 0.0,
      totalEarnings: (map['totalEarnings'] as num?)?.toDouble() ?? 0.0,
      totalWithdrawn: (map['totalWithdrawn'] as num?)?.toDouble() ?? 0.0,
      isEmailVerified: isEmailVerified,
      isActive: map['isActive'] as bool? ?? true,
      profileCompleted: map['profileCompleted'] as bool? ?? false,
      dateOfBirth: map['dateOfBirth'] as String?,
      gender: map['gender'] as String?,
      address: map['address'] as String?,
      city: map['city'] as String?,
      state: map['state'] as String?,
      country: map['country'] as String?,
      username: map['username'] as String?,
      profilePicture: map['profilePicture'] as String?,
      coverImage: map['coverImage'] as String?,
      aboutMe: map['aboutMe'] as String?,
      education: map['education'] as String?,
      portfolioLinks: portfolioList,
      resumeUrl: map['resumeUrl'] as String?,
      certificateUrl: map['certificateUrl'] as String?,
      isVerified: map['isVerified'] as bool? ?? false,
      profileCompletionPercentage: (map['profileCompletionPercentage'] as num?)?.toInt() ?? 0,
    );
  }

  Map<String, dynamic> toFirestore() {
    return {
      'uid': uid,
      'firstName': firstName,
      'lastName': lastName,
      'fullName': fullName,
      'email': email,
      if (phone != null) 'phone': phone,
      'referralCode': referralCode,
      if (referralCodeUsed != null) 'referralCodeUsed': referralCodeUsed,
      'createdAt': createdAt,
      if (lastLoginAt != null) 'lastLoginAt': lastLoginAt,
      'walletBalance': walletBalance,
      'totalEarnings': totalEarnings,
      'totalWithdrawn': totalWithdrawn,
      'isActive': isActive,
      'profileCompleted': profileCompleted,
      if (dateOfBirth != null) 'dateOfBirth': dateOfBirth,
      if (gender != null) 'gender': gender,
      if (address != null) 'address': address,
      if (city != null) 'city': city,
      if (state != null) 'state': state,
      if (country != null) 'country': country,
      if (username != null) 'username': username,
      if (profilePicture != null) 'profilePicture': profilePicture,
      if (coverImage != null) 'coverImage': coverImage,
      if (aboutMe != null) 'aboutMe': aboutMe,
      if (portfolioLinks.isNotEmpty) 'portfolioLinks': portfolioLinks,
      if (resumeUrl != null) 'resumeUrl': resumeUrl,
      if (certificateUrl != null) 'certificateUrl': certificateUrl,
      'isVerified': isVerified,
      'profileCompletionPercentage': profileCompletionPercentage,
    };
  }

  UserModel copyWithModel({
    String? uid,
    String? firstName,
    String? lastName,
    String? fullName,
    String? email,
    String? phone,
    String? referralCode,
    String? referralCodeUsed,
    DateTime? createdAt,
    DateTime? lastLoginAt,
    double? walletBalance,
    double? totalEarnings,
    double? totalWithdrawn,
    bool? isEmailVerified,
    bool? isActive,
    bool? profileCompleted,
    String? dateOfBirth,
    String? gender,
    String? address,
    String? city,
    String? state,
    String? country,
    String? username,
    String? profilePicture,
    String? coverImage,
    String? aboutMe,
    String? education,
    String? experience,
    List<String>? portfolioLinks,
    String? resumeUrl,
    String? certificateUrl,
    bool? isVerified,
    int? profileCompletionPercentage,
  }) {
    return UserModel(
      uid: uid ?? this.uid,
      firstName: firstName ?? this.firstName,
      lastName: lastName ?? this.lastName,
      fullName: fullName ?? this.fullName,
      email: email ?? this.email,
      phone: phone ?? this.phone,
      referralCode: referralCode ?? this.referralCode,
      referralCodeUsed: referralCodeUsed ?? this.referralCodeUsed,
      createdAt: createdAt ?? this.createdAt,
      lastLoginAt: lastLoginAt ?? this.lastLoginAt,
      walletBalance: walletBalance ?? this.walletBalance,
      totalEarnings: totalEarnings ?? this.totalEarnings,
      totalWithdrawn: totalWithdrawn ?? this.totalWithdrawn,
      isEmailVerified: isEmailVerified ?? this.isEmailVerified,
      isActive: isActive ?? this.isActive,
      profileCompleted: profileCompleted ?? this.profileCompleted,
      dateOfBirth: dateOfBirth ?? this.dateOfBirth,
      gender: gender ?? this.gender,
      address: address ?? this.address,
      city: city ?? this.city,
      state: state ?? this.state,
      country: country ?? this.country,
      username: username ?? this.username,
      profilePicture: profilePicture ?? this.profilePicture,
      coverImage: coverImage ?? this.coverImage,
      aboutMe: aboutMe ?? this.aboutMe,
      education: education ?? this.education,
      experience: experience ?? this.experience,
      portfolioLinks: portfolioLinks ?? this.portfolioLinks,
      resumeUrl: resumeUrl ?? this.resumeUrl,
      certificateUrl: certificateUrl ?? this.certificateUrl,
      isVerified: isVerified ?? this.isVerified,
      profileCompletionPercentage: profileCompletionPercentage ?? this.profileCompletionPercentage,
    );
  }
}
